const LANG_KEY = 'kiosk.lang';
const listeners = new Set();

function initialLang() {
  if (typeof window === 'undefined') return 'en';
  const fromUrl = new URLSearchParams(location.search).get('lang');
  if (LANGS.includes(fromUrl)) {
    writeSetting(LANG_KEY, fromUrl);
    return fromUrl;
  }
  const saved = readSetting(LANG_KEY);
  if (LANGS.includes(saved)) return saved;
  const browser = navigator.language.slice(0, 2).toLowerCase();
  return LANGS.includes(browser) ? browser : 'en';
}

let current = initialLang();

function change(lang) {
  current = lang;
  if (typeof document !== 'undefined') document.documentElement.lang = lang;
  for (const listener of listeners) listener();
}

if (typeof document !== 'undefined') document.documentElement.lang = current;

export const getLang = () => current;
export const localeTag = () => (current === 'tr' ? 'tr-TR' : 'en-US');

export function subscribeLang(listener) {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

export function setLang(lang) {
  if (!LANGS.includes(lang) || lang === current) return;
  writeSetting(LANG_KEY, lang);
  change(lang);
}

export function applyServerLocale(locale) {
  const lang = String(locale ?? '').slice(0, 2).toLowerCase();
  if (!readSetting(LANG_KEY) && LANGS.includes(lang) && lang !== current) change(lang);
}

export function t(key, vars = {}) {
  const template = DICT[current][key] ?? DICT.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, name) => (name in vars ? String(vars[name]) : match));
}
